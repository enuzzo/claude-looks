// A diagnostic, not a look: abyssal with one part taken out in each variant, to find what makes the
// desktop app stop a backdrop a few seconds in. Run: node tools/scenes/lab.mjs
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { SCENE } from '../../hooks/looks/abyssal/scene.js'

const ROOT = join(fileURLToPath(import.meta.url), '../../..')

// cut a <g> that opens with `start`, with everything it holds
function cut(svg, start) {
  const a = svg.indexOf(start)
  if (a < 0) throw new Error(`no ${start}`)
  const tags = /<(\/?)g\b[^>]*?(\/?)>/g
  tags.lastIndex = a
  let depth = 0, t
  while ((t = tags.exec(svg))) {
    if (t[2] === '/') continue
    depth += t[1] ? -1 : 1
    if (depth === 0) return svg.slice(0, a) + svg.slice(t.index + t[0].length)
  }
  throw new Error(`unclosed ${start}`)
}
const PLANK = '<g class="plank">', JELLY = '<g class="jelly">', MANTA = '<g class="manta"', TURTLE = '<g class="visitor">'
const VARIANTS = [
  ['lab-1', 'no plankton', s => cut(s, PLANK)],
  ['lab-2', 'no jellies', s => cut(s, JELLY)],
  ['lab-3', 'no manta', s => cut(s, MANTA)],
  ['lab-4', 'no turtle', s => cut(s, TURTLE)],
  ['lab-5', 'glows only', s => [PLANK, JELLY, MANTA, TURTLE].reduce(cut, s)],
  ['lab-6', 'no reduce-motion rule', s => s.replace(/@media \(prefers-reduced-motion:reduce\)\{[^{}]*(\{[^{}]*\}[^{}]*)*\}/, '')],
]
const out = VARIANTS.map(([id, label, f]) => {
  const source = f(SCENE)
  if (source === SCENE) throw new Error(`${id} changed nothing`)
  return { id, label, source }
})
writeFileSync(join(ROOT, 'hooks/looks/lab/scenes.js'),
  `// Generated by tools/scenes/lab.mjs: abyssal with one part taken out in each variant.\nexport const VARIANTS = ${JSON.stringify(out)}\n`)
for (const v of out) console.log(v.id, v.label, v.source.length)
